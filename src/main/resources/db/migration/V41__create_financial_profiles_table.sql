CREATE TABLE financial_profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    financial_trend JSONB NOT NULL DEFAULT '{}'::jsonb,
    financial_moment JSONB NOT NULL DEFAULT '{}'::jsonb,
    main_strength JSONB NOT NULL DEFAULT '{}'::jsonb,
    key_opportunity JSONB NOT NULL DEFAULT '{}'::jsonb,
    current_area_of_focus JSONB NOT NULL DEFAULT '{}'::jsonb,
    main_attention JSONB NOT NULL DEFAULT '{}'::jsonb,
    confidence_score INTEGER NOT NULL,
    confidence_in_the_result JSONB NOT NULL DEFAULT '{}'::jsonb,
    interpretive_synthesis TEXT NOT NULL,
    general_financial_index INTEGER NOT NULL,
    financial_security INTEGER NOT NULL,
    financial_resilience INTEGER NOT NULL,
    organization_and_control INTEGER NOT NULL,
    impulse_regulation INTEGER NOT NULL,
    orientation_the_future INTEGER NOT NULL,
    balance_and_freedom INTEGER NOT NULL,
    registered_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_financial_profiles_user UNIQUE (user_id),
    CONSTRAINT ck_financial_profiles_confidence_score CHECK (confidence_score BETWEEN 0 AND 100),
    CONSTRAINT ck_financial_profiles_general_index CHECK (general_financial_index BETWEEN 0 AND 100),
    CONSTRAINT ck_financial_profiles_security CHECK (financial_security BETWEEN 0 AND 100),
    CONSTRAINT ck_financial_profiles_resilience CHECK (financial_resilience BETWEEN 0 AND 100),
    CONSTRAINT ck_financial_profiles_organization CHECK (organization_and_control BETWEEN 0 AND 100),
    CONSTRAINT ck_financial_profiles_impulse CHECK (impulse_regulation BETWEEN 0 AND 100),
    CONSTRAINT ck_financial_profiles_future CHECK (orientation_the_future BETWEEN 0 AND 100),
    CONSTRAINT ck_financial_profiles_balance CHECK (balance_and_freedom BETWEEN 0 AND 100)
);
